export function normalizeBusinessSlug(slug: string): string {
  if (slug === "happy-adventure") return "happy-adventure-camp";
  if (slug === "tour-planner") return "elite-india-tour-planner";
  return slug;
}

export function getBusinessImages(slug: string): BusinessImage[] {
  const norm = normalizeBusinessSlug(slug);
  return BUSINESS_IMAGE_MAP[norm] || [];
}

export function getBusinessHeroImage(slug: string): string {
  const images = getBusinessImages(slug);
  return images[0]?.url || "/businesses/mr-desert/6-scaled-e1756826347412.webp";
}

export function getFeaturedCardImages(slug: string): string[] {
  const images = getBusinessImages(slug);
  return images.map((img) => img.url);
}

export function getAllBusinessImages(): BusinessImage[] {
  return Object.values(BUSINESS_IMAGE_MAP).flat();
}
